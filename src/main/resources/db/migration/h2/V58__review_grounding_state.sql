-- Operational state for grounded PR reviews: findings, revision cursors, and per-PR run leases.
CREATE TABLE review_finding (
    id UUID PRIMARY KEY,
    marker VARCHAR(128) NOT NULL UNIQUE,
    bot_id BIGINT NOT NULL,
    repo_owner VARCHAR(255) NOT NULL,
    repo_name VARCHAR(255) NOT NULL,
    pr_number BIGINT NOT NULL,
    workflow_key VARCHAR(64) NOT NULL,
    path VARCHAR(2048),
    side VARCHAR(16),
    line INTEGER,
    quote TEXT,
    quote_hash VARCHAR(64),
    context_hash VARCHAR(64),
    severity VARCHAR(32),
    category VARCHAR(64),
    body TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    summary_only BOOLEAN NOT NULL,
    remote_comment_id VARCHAR(255),
    remote_thread_id VARCHAR(255),
    last_answered_comment_id VARCHAR(255),
    head_sha VARCHAR(128),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_review_finding_scope_status
    ON review_finding (bot_id, repo_owner, repo_name, pr_number, workflow_key, status);

CREATE TABLE review_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id BIGINT NOT NULL,
    repo_owner VARCHAR(255) NOT NULL,
    repo_name VARCHAR(255) NOT NULL,
    pr_number BIGINT NOT NULL,
    workflow_key VARCHAR(64) NOT NULL,
    head_sha VARCHAR(128),
    effective_base_sha VARCHAR(128),
    reviewed_at TIMESTAMP NOT NULL,
    degraded BOOLEAN NOT NULL,
    last_seen_comment_at TIMESTAMP,
    last_seen_comment_id VARCHAR(255),
    pr_closed_at TIMESTAMP,
    CONSTRAINT uk_review_revision_scope
        UNIQUE (bot_id, repo_owner, repo_name, pr_number, workflow_key)
);
CREATE INDEX idx_review_revision_closed ON review_revision (pr_closed_at);

CREATE TABLE review_run_lease (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id BIGINT NOT NULL,
    repo_owner VARCHAR(255) NOT NULL,
    repo_name VARCHAR(255) NOT NULL,
    pr_number BIGINT NOT NULL,
    lease_owner VARCHAR(36),
    lease_token BIGINT NOT NULL,
    lease_expires_at TIMESTAMP,
    CONSTRAINT uk_review_run_lease_scope
        UNIQUE (bot_id, repo_owner, repo_name, pr_number)
);
